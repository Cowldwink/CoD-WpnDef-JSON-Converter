#  Import the WpnDef file
# ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ 
function fnConvWpnD {
    param (
        [Parameter(Mandatory)][array]$aWpnDFiles,
        [switch]$bFromJson
    )

    foreach ($sWpnDFile in $aWpnDFiles) {
        if ($bFromJson) {
            $oWpnDData = Get-Content $sWpnDFile -Raw | ConvertFrom-Json
            $sWpnDNewData = 'WEAPONFILE'

            foreach ($oWpnDAttr in $oWpnDData.PSObject.Properties) {
                $sWpnDNewData = $sWpnDNewData + '\' + "$($oWpnDAttr.Name)" + '\' + "$(($oWpnDAttr.Value) -join '`n')"
            }

            #  Output file
            # ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ 
            $sWpnDOutFile = "$sOutDir\$((Split-Path $sWpnDFile -Leaf).Replace('.json' , ''))"
            if ($sWpnDNewData.Contains('`n')) {
                $aWpnDNewData = $sWpnDNewData -split '`n'
            } else {
                $aWpnDNewData = @();$aWpnDNewData += $sWpnDNewData
            }

            $oSW = [System.IO.StreamWriter]::new(
                $sWpnDOutFile,
                $false,
                $oUtf8Enc
            )

            for ($i = 0; $i -lt $aWpnDNewData.Count; $i++) {
                $oSW.Write($aWpnDNewData[$i])

                if ($i -lt $aWpnDNewData.Count - 1) {
                    $oSW.Write([Environment]::NewLine)
                }
            }

            $oSW.Dispose()
        } else {
            $sWpnDData = Get-Content $sWpnDFile -Raw
            $hWpnDNewData = [ordered]@{}

            #  Format check
            # ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ 
            if (-not ($sWpnDData).StartsWith('WEAPONFILE\')) {
                fnWinMsgBox `
                    "Error" `
                    "Invalid WeaponDef file selected.`n $sWpnDFile" `
                    1 | Out-Null
                Continue
            } else {
                $aWpnDData = ($sWpnDData.Substring(11)).Split('\')
            }

            #  Convert to hashtable
            # ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ 
            for ($i = 0; $i -lt ([regex]::Matches($sWpnDData, '\\')).Count; $i += 2) {
                $hWpnDNewData[$aWpnDData[$i]] = if ($aWpnDData[$i + 1] -match "[\r\n]") {
                        $aWpnDData[$i + 1] -split '\r?\n'
                    } else {
                        $aWpnDData[$i + 1]
                    }
            }

            #  Output file
            # ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ 
            $sWpnDOutFile = "$sOutDir\$(Split-Path $sWpnDFile -Leaf).json"
            [System.IO.File]::WriteAllLines(
                "$sWpnDOutFile",
                (ConvertTo-Json -InputObject $hWpnDNewData),
                $oUtf8Enc
            )
        }
    }

    fnWinMsgBox `
        "Information" `
        "Produced converted WeaponDef file(s) at: $sOutDir" `
        4 | Out-Null
}


                $aWpnDData[$i + 1] -split '\r?\n'
            } else {
                $aWpnDData[$i + 1]
            }
    }

    #  Get WpnDef file to use as template
    # ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ 
    $sWpnDTempFile = fnFileSel `
        "Select the CoD WeaponDef file(s) to port" `
        "All Files (*.*)|*.*" `
        "$PSScriptRoot\Data\Templates"

    #  Format check
    # ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ 
    $sWpnDTempFile = Get-Content $sWpnDTempFile -Raw
    if (-not ($sWpnDTempFile).StartsWith('WEAPONFILE\')) {
        fnWinMsgBox `
            "Error" `
            "Invalid WeaponDef file selected.`n $sWpnDFile" `
            1 | Out-Null
        Return
    } else {
        $aWpnDData = ($sWpnDTempFile.Substring(11)).Split('\')
    }

    #  Convert to hashtable
    # ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ 
    $hWpnDNewData = [ordered]@{}
    for ($i = 0; $i -lt ([regex]::Matches($sWpnDTempFile, '\\')).Count; $i += 2) {
        $hWpnDNewData[$aWpnDData[$i]] = if ($aWpnDData[$i + 1] -match "[\r\n]") {
                $aWpnDData[$i + 1] -split '\r?\n'
            } else {
                $aWpnDData[$i + 1]
            }
    }

    #  Apply similar named keys
    # ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ 
    foreach ($sKey in $hWpnDOgData.Keys) {
        if ($hWpnDNewData.Contains($sKey)) {
            $hWpnDNewData[$sKey] = $hWpnDOgData[$sKey]
        }
    }

    #  Prepare WpnDef for output
    # ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ 
    $sWpnDNewData = 'WEAPONFILE'

    foreach ($sKey in $hWpnDNewData.Keys) {
        $sWpnDNewData = $sWpnDNewData + '\' + "$sKey" + '\' + "$($hWpnDNewData[$sKey] -join '`n')"
    }

    if ($sWpnDNewData.Contains('`n')) {
        $aWpnDNewData = $sWpnDNewData -split '`n'
    } else {
        $aWpnDNewData = @();$aWpnDNewData += $sWpnDNewData
    }

    #  Output file
    # ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ ̅ 
    $sWpnDOutFile = "$sOutDir\$(Split-Path $sWpnDFile -Leaf)"
    $oSW = [System.IO.StreamWriter]::new(
        $sWpnDOutFile,
        $false,
        $oUtf8Enc
    )

    for ($i = 0; $i -lt $aWpnDNewData.Count; $i++) {
        $oSW.Write($aWpnDNewData[$i])

        if ($i -lt $aWpnDNewData.Count - 1) {
            $oSW.Write([Environment]::NewLine)
        }
    }

    $oSW.Dispose()

    fnWinMsgBox `
        "Information" `
        "Ported WeaponDef file to: $sWpnDOutFile" `
        4 | Out-Null
}

